# Python operators examples

# Arithmetic operators
x = 10
y = 3
print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Floor Division:", x // y)
print("Modulus:", x % y)
print("Exponentiation:", x ** y)

# Comparison operators
print("Equal:", x == y)
print("Not equal:", x != y)
print("Greater than:", x > y)
print("Less than:", x < y)

# Logical operators
is_valid = True
is_active = False
print("AND:", is_valid and is_active)
print("OR:", is_valid or is_active)
print("NOT:", not is_valid)

# Assignment operators
value = 5
value += 2
value *= 3
print("Assignment result:", value)

# Identity operators
print("Same object:", x is y)
print("Different object:", x is not y)

# Membership operators
letters = ["a", "b", "c"]
print("Membership:", "b" in letters)
print("Not in:", "d" not in letters)


